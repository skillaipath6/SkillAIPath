# DBTITLE 1,Business Scenario 1 - Churn Risk Scoring
# Identify customers at risk of churning
df_churn_risk = spark.sql(f"""
    WITH churn_signals AS (
      SELECT
        CustomerSK,
        CustomerName,
        customer_segment,
        days_since_last_purchase,
        total_orders,
        lifetime_value,

        -- Churn risk factors (0-100 scale)
        CASE
          WHEN days_since_last_purchase > 180 THEN 40
          WHEN days_since_last_purchase > 90 THEN 25
          WHEN days_since_last_purchase > 60 THEN 15
          WHEN days_since_last_purchase > 30 THEN 5
          ELSE 0
        END AS recency_risk,

        CASE
          WHEN total_orders >= 20 THEN 0
          WHEN total_orders >= 10 THEN 10
          WHEN total_orders >= 5 THEN 20
          ELSE 30
        END AS frequency_risk,

        CASE
          WHEN avg_order_value < 2000 THEN 15
          WHEN avg_order_value < 5000 THEN 10
          ELSE 0
        END AS monetary_risk,

        -- Behavioral risk
        CASE
          WHEN DATEDIFF(last_purchase_date, first_purchase_date) < 30 THEN 15  -- Short tenure
          ELSE 0
        END AS tenure_risk

      FROM {Config.TBL_MART_CUSTOMER_360}
    )
    SELECT
      CustomerSK,
      CustomerName,
      customer_segment,
      days_since_last_purchase,
      total_orders,
      ROUND(lifetime_value / 100000, 2) as ltv_lakhs,

      -- Aggregate churn score
      (recency_risk + frequency_risk + monetary_risk + tenure_risk) AS churn_risk_score,

      CASE
        WHEN (recency_risk + frequency_risk + monetary_risk + tenure_risk) >= 70 THEN 'CRITICAL'
        WHEN (recency_risk + frequency_risk + monetary_risk + tenure_risk) >= 50 THEN 'HIGH'
        WHEN (recency_risk + frequency_risk + monetary_risk + tenure_risk) >= 30 THEN 'MEDIUM'
        ELSE 'LOW'
      END AS churn_risk_level,

      -- Recommended action
      CASE
        WHEN (recency_risk + frequency_risk + monetary_risk + tenure_risk) >= 70 AND lifetime_value > 100000
          THEN 'VIP Win-Back Call + 40% Off'
        WHEN (recency_risk + frequency_risk + monetary_risk + tenure_risk) >= 50
          THEN 'Reactivation Email Series'
        WHEN (recency_risk + frequency_risk + monetary_risk + tenure_risk) >= 30
          THEN 'Engagement Survey'
        ELSE 'Monitor'
      END AS recommended_intervention

    FROM churn_signals
    WHERE (recency_risk + frequency_risk + monetary_risk + tenure_risk) >= 50  -- High/Critical risk only
    ORDER BY churn_risk_score DESC, ltv_lakhs ASC
    LIMIT 100
""")

print("Business Impact: Customers at CRITICAL/HIGH churn risk")
