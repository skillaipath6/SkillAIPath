# DBTITLE 1,Business Scenario 6 - Lifetime Value Prediction
# Project 3-year CLV based on historical patterns
df_clv_prediction = spark.sql(f"""
    WITH customer_velocity AS (
      SELECT
        CustomerSK,
        CustomerName,
        customer_segment,
        lifetime_value AS historical_ltv,
        total_orders,
        DATEDIFF(last_purchase_date, first_purchase_date) AS tenure_days,
        CASE
          WHEN DATEDIFF(last_purchase_date, first_purchase_date) > 0
            THEN total_orders / (DATEDIFF(last_purchase_date, first_purchase_date) / 365.0)
          ELSE total_orders
        END AS orders_per_year,
        CASE
          WHEN total_orders > 0
            THEN lifetime_value / total_orders
          ELSE 0
        END AS avg_order_value
      FROM {Config.TBL_MART_CUSTOMER_360}
      WHERE DATEDIFF(CURRENT_DATE(), last_purchase_date) <= 180
    )
    SELECT
      CustomerName,
      customer_segment,
      ROUND(historical_ltv / 100000, 2) AS historical_ltv_lakhs,
      ROUND(orders_per_year, 1) AS orders_per_year,
      ROUND(avg_order_value / 1000, 2) AS avg_order_value_thousands,
      ROUND((orders_per_year * avg_order_value * 3) / 100000, 2) AS projected_3yr_clv_lakhs
    FROM customer_velocity
    WHERE orders_per_year > 0
    ORDER BY projected_3yr_clv_lakhs DESC
    LIMIT 100
""")

