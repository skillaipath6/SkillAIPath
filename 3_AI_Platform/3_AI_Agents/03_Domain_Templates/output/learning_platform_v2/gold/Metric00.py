# DBTITLE 1,Business Scenario 4 - Cohort Retention Analysis
# Analyze customer retention by signup cohort (month)
df_cohort_retention = spark.sql(f"""
    WITH customer_cohorts AS (
      SELECT
        CustomerSK,
        DATE_TRUNC('MONTH', first_purchase_date) AS cohort_month,
        DATEDIFF(last_purchase_date, first_purchase_date) AS tenure_days,
        total_orders,
        lifetime_value,
        CASE
          WHEN days_since_last_purchase <= 30 THEN 'Active'
          WHEN days_since_last_purchase <= 90 THEN 'Dormant'
          ELSE 'Churned'
        END AS current_status
      FROM {Config.TBL_MART_CUSTOMER_360}
    ),
    cohort_summary AS (
      SELECT
        cohort_month,
        COUNT(*) AS cohort_size,
        SUM(CASE WHEN current_status = 'Active' THEN 1 ELSE 0 END) AS still_active,
        ROUND(SUM(CASE WHEN current_status = 'Active' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS retention_rate,
        ROUND(AVG(tenure_days), 0) AS avg_tenure_days,
        ROUND(AVG(total_orders), 1) AS avg_orders_per_customer,
        ROUND(AVG(lifetime_value) / 100000, 2) AS avg_ltv_lakhs
      FROM customer_cohorts
      GROUP BY cohort_month
    )
    SELECT
      cohort_month,
      cohort_size,
      still_active,
      CONCAT(retention_rate, '%') AS retention_rate,
      avg_tenure_days,
      avg_orders_per_customer,
      CONCAT('₹', avg_ltv_lakhs, ' L') AS avg_customer_ltv
    FROM cohort_summary
    ORDER BY cohort_month DESC
    LIMIT 12
""")

