# DBTITLE 1,Business Scenario 3 - Customer Health Score
# Calculate 0-100 health score based on multiple engagement factors

from pyspark.sql.functions import col, when, round as spark_round, current_date, datediff

df_customer_360 = spark.table(Config.TBL_MART_CUSTOMER_360)

# Calculate health score components
df_health = df_customer_360.withColumn(
    "recency_score",
    when(col("days_since_last_purchase") <= 30, 25)
    .when(col("days_since_last_purchase") <= 60, 20)
    .when(col("days_since_last_purchase") <= 90, 15)
    .when(col("days_since_last_purchase") <= 180, 10)
    .otherwise(5)
).withColumn(
    "frequency_score",
    when(col("total_orders") >= 20, 25)
    .when(col("total_orders") >= 10, 20)
    .when(col("total_orders") >= 5, 15)
    .when(col("total_orders") >= 2, 10)
    .otherwise(5)
).withColumn(
    "monetary_score",
    when(col("lifetime_value") >= 500000, 25)
    .when(col("lifetime_value") >= 200000, 20)
    .when(col("lifetime_value") >= 100000, 15)
    .when(col("lifetime_value") >= 50000, 10)
    .otherwise(5)
).withColumn(
    "engagement_score",
    when(col("unique_products_purchased") >= 10, 25)
    .when(col("unique_products_purchased") >= 5, 20)
    .when(col("unique_products_purchased") >= 3, 15)
    .when(col("unique_products_purchased") >= 2, 10)
    .otherwise(5)
).withColumn(
    "health_score",
    col("recency_score") + col("frequency_score") + col("monetary_score") + col("engagement_score")
).withColumn(
    "health_tier",
    when(col("health_score") >= 80, "EXCELLENT")
    .when(col("health_score") >= 60, "GOOD")
    .when(col("health_score") >= 40, "FAIR")
    .otherwise("POOR")
)

