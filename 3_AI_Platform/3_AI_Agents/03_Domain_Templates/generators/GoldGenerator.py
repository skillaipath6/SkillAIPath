"""
GOLD LAYER GENERATOR - Production Grade
Replicates SkillAIPath gold analytics patterns (Customer 360, RFM, Product Performance, etc.)
Creates comprehensive business metrics
"""
import re
from pathlib import Path
from typing import Dict, List

class GoldGenerator:
    """Generate gold layer with SkillAIPath analytics patterns"""
    
    def __init__(self, skillaipath_root: str, config: Dict):
        self.skillaipath = Path(skillaipath_root)
        self.config = config
        self.catalog = config['domain']['catalog']
        self.domain = config['domain']['name']
        
        # SkillAIPath gold patterns
        self.gold_path = self.skillaipath / "2_Data_Production/02_Medallion_Architecture/04_Gold"
    
    def generate_all_metrics(self) -> List[str]:
        """Generate all gold metric tables"""
        notebooks = []
        
        for metric in self.config.get('gold', {}).get('metrics', []):
            source_pattern = metric.get('source_pattern', 'mart_customer_360')
            notebook = self._replicate_metric_from_pattern(metric, source_pattern)
            notebooks.append(notebook)
        
        return notebooks
    
    def _replicate_metric_from_pattern(self, metric_config: Dict, pattern_name: str) -> str:
        """Replicate gold metric from SkillAIPath"""
        target_name = metric_config['name']
        
        # Find pattern file
        pattern_file = self._find_gold_pattern(pattern_name)
        
        if not pattern_file:
            return self._generate_simple_metric(metric_config)
        
        print(f"   Replicating {target_name} from {pattern_file.name}")
        
        # Read pattern
        with open(pattern_file, 'r') as f:
            pattern_code = f.read()
        
        # Adapt to domain
        adapted = self._adapt_gold_code(pattern_code, target_name, metric_config)
        
        return adapted
    
    def _find_gold_pattern(self, pattern_name: str) -> Path:
        """Find gold pattern file"""
        for file in self.gold_path.glob("*.py"):
            if pattern_name.lower() in file.stem.lower():
                return file
        
        # Fuzzy match
        for file in self.gold_path.glob("*.py"):
            if 'mart' in file.stem.lower() or 'gold' in file.stem.lower():
                if any(word in file.stem.lower() for word in pattern_name.lower().split('_')):
                    return file
        
        return None
    
    def _adapt_gold_code(self, source_code: str, target_table: str, config: Dict) -> str:
        """Adapt gold analytics code"""
        
        # Replace catalog
        adapted = source_code.replace('sap_sample', self.catalog)
        
        # Replace table name
        original_table = self._extract_table_name(source_code)
        if original_table:
            adapted = adapted.replace(original_table, target_table)
        
        # Adapt metric calculations if specified
        if config.get('metrics'):
            adapted = self._inject_metric_calculations(adapted, config['metrics'])
        
        # Add header
        header = f'''"""
Gold Metric: {target_table}
Domain: {self.domain}
Pattern: Business analytics (replicated from SkillAIPath)
Catalog: {self.catalog}

Description: {config.get('description', 'Comprehensive business metrics')}

Auto-generated by Domain Templates V2
"""

'''
        adapted = header + adapted
        
        return adapted
    
    def _extract_table_name(self, code: str) -> str:
        """Extract table name"""
        match = re.search(r"(mart_\w+|gold_\w+)", code)
        return match.group(1) if match else None
    
    def _inject_metric_calculations(self, code: str, metrics: List[str]) -> str:
        """Inject custom metric calculations"""
        metric_section = "\n".join([
            f"    # Metric: {metric}" for metric in metrics
        ])
        
        code = code.replace(
            "# Metric calculations",
            f"# Custom metrics\n{metric_section}\n\n# Metric calculations"
        )
        
        return code
    
    def _generate_simple_metric(self, config: Dict) -> str:
        """Generate basic metric (fallback)"""
        return f"# Generated metric: {config['name']}\n"
    
    def save_notebooks(self, notebooks: List[str], output_dir: Path):
        """Save gold notebooks"""
        output_dir.mkdir(parents=True, exist_ok=True)
        
        for i, notebook in enumerate(notebooks):
            lines = notebook.split('\n')
            name = f"gold_{i:02d}.py"
            for line in lines[:20]:
                if 'Gold Metric:' in line:
                    name = line.split(':')[1].strip() + '.py'
                    break
            
            output_path = output_dir / name
            with open(output_path, 'w') as f:
                f.write(notebook)
            
            print(f"   ✅ Saved {name}")

if __name__ == '__main__':
    print("Gold Generator Ready")
