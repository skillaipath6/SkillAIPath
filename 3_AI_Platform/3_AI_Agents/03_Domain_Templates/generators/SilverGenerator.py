"""
SILVER LAYER GENERATOR - Production Grade
Replicates SkillAIPath dimension and fact patterns to new domains
Preserves complex logic: SCD2, bridge tables, complex joins
"""
import re
from pathlib import Path
from typing import Dict, List

class SilverGenerator:
    """Generate silver layer with SkillAIPath pattern replication"""
    
    def __init__(self, skillaipath_root: str, config: Dict):
        self.skillaipath = Path(skillaipath_root)
        self.config = config
        self.catalog = config['domain']['catalog']
        self.domain = config['domain']['name']
        
        # SkillAIPath pattern paths
        self.dim_path = self.skillaipath / "2_Data_Production/02_Medallion_Architecture/01_Dimensions"
        self.fact_path = self.skillaipath / "2_Data_Production/02_Medallion_Architecture/02_Facts"
    
    def generate_all_dimensions(self) -> List[str]:
        """Generate all dimension notebooks from patterns"""
        notebooks = []
        
        for dim in self.config.get('silver', {}).get('dimensions', []):
            pattern_type = dim.get('pattern', 'scd1')
            source_pattern = dim.get('source_pattern', None)
            
            if source_pattern:
                notebook = self._replicate_dimension_from_pattern(dim, source_pattern)
            else:
                notebook = self._generate_dimension(dim, pattern_type)
            
            notebooks.append(notebook)
        
        return notebooks
    
    def _replicate_dimension_from_pattern(self, dim_config: Dict, pattern_name: str) -> str:
        """Replicate dimension from specific SkillAIPath pattern"""
        target_name = dim_config['name']
        
        pattern_file = self._find_pattern_file(self.dim_path, pattern_name)
        
        if not pattern_file:
            return self._generate_dimension(dim_config, 'scd1')
        
        print(f"   Replicating {target_name} from {pattern_file.name}")
        
        with open(pattern_file, 'r') as f:
            pattern_code = f.read()
        
        adapted = self._adapt_dimension_code(pattern_code, target_name, dim_config)
        
        return adapted
    
    def _find_pattern_file(self, pattern_dir: Path, pattern_name: str) -> Path:
        """Find pattern file by name"""
        for file in pattern_dir.glob("*.py"):
            if pattern_name.lower() in file.stem.lower():
                return file
        
        for file in pattern_dir.glob("*.py"):
            if any(word in file.stem.lower() for word in pattern_name.lower().split('_')):
                return file
        
        return None
    
    def _adapt_dimension_code(self, source_code: str, target_table: str, config: Dict) -> str:
        """Adapt dimension code to new domain"""
        
        adapted = source_code.replace('sap_sample', self.catalog)
        
        if 'scd2' in source_code.lower():
            pattern_type = 'SCD2'
        elif 'scd1' in source_code.lower():
            pattern_type = 'SCD1'
        else:
            pattern_type = 'Simple'
        
        original_table = self._extract_table_name(source_code)
        if original_table:
            adapted = adapted.replace(original_table, target_table)
        
        if config.get('source'):
            adapted = self._replace_source_table(adapted, config['source'])
        
        header = f"""# Dimension: {target_table}
# Domain: {self.domain}
# Pattern: {pattern_type} (replicated from SkillAIPath)
# Catalog: {self.catalog}
# Auto-generated by Domain Templates V2

"""
        adapted = header + adapted
        
        return adapted
    
    def _extract_table_name(self, code: str) -> str:
        """Extract table name from pattern code"""
        match = re.search(r"(dim_\w+)", code)
        return match.group(1) if match else None
    
    def _replace_source_table(self, code: str, source_table: str) -> str:
        """Replace bronze source table reference"""
        code = re.sub(
            r'bronze\.(\w+)',
            f'bronze.{source_table}',
            code,
            count=1
        )
        return code
    
    def generate_all_facts(self) -> List[str]:
        """Generate all fact notebooks from patterns"""
        notebooks = []
        
        for fact in self.config.get('silver', {}).get('facts', []):
            source_pattern = fact.get('source_pattern', 'fact_sales')
            notebook = self._replicate_fact_from_pattern(fact, source_pattern)
            notebooks.append(notebook)
        
        return notebooks
    
    def _replicate_fact_from_pattern(self, fact_config: Dict, pattern_name: str) -> str:
        """Replicate fact from SkillAIPath pattern"""
        target_name = fact_config['name']
        
        pattern_file = self._find_pattern_file(self.fact_path, pattern_name)
        
        if not pattern_file:
            return self._generate_simple_fact(fact_config)
        
        print(f"   Replicating {target_name} from {pattern_file.name}")
        
        with open(pattern_file, 'r') as f:
            pattern_code = f.read()
        
        adapted = self._adapt_fact_code(pattern_code, target_name, fact_config)
        
        return adapted
    
    def _adapt_fact_code(self, source_code: str, target_table: str, config: Dict) -> str:
        """Adapt fact code with custom joins"""
        
        adapted = source_code.replace('sap_sample', self.catalog)
        
        original_table = self._extract_table_name(source_code)
        if original_table:
            adapted = adapted.replace(original_table, target_table)
        
        if config.get('joins'):
            adapted = self._inject_custom_joins(adapted, config['joins'])
        
        header = f"""# Fact: {target_table}
# Domain: {self.domain}
# Pattern: Multi-table join (replicated from SkillAIPath)
# Catalog: {self.catalog}
# Joins: {', '.join(config.get('joins', []))}
# Auto-generated by Domain Templates V2

"""
        adapted = header + adapted
        
        return adapted
    
    def _inject_custom_joins(self, code: str, join_tables: List[str]) -> str:
        """Inject custom join logic"""
        join_section = "\n".join([
            f"    # JOIN with {table}" for table in join_tables
        ])
        
        code = code.replace(
            "# Begin transformations",
            f"# Custom joins\n{join_section}\n\n# Begin transformations"
        )
        
        return code
    
    def _generate_dimension(self, dim_config: Dict, pattern_type: str) -> str:
        """Generate basic dimension (fallback)"""
        return f"# Generated dimension: {dim_config['name']} ({pattern_type})\n"
    
    def _generate_simple_fact(self, fact_config: Dict) -> str:
        """Generate basic fact (fallback)"""
        return f"# Generated fact: {fact_config['name']}\n"
    
    def save_notebooks(self, notebooks: List[str], output_dir: Path):
        """Save generated notebooks"""
        output_dir.mkdir(parents=True, exist_ok=True)
        
        for i, notebook in enumerate(notebooks):
            lines = notebook.split('\n')
            name = f"silver_{i:02d}.py"
            for line in lines[:20]:
                if 'Dimension:' in line or 'Fact:' in line:
                    name = line.split(':')[1].strip() + '.py'
                    break
            
            output_path = output_dir / name
            with open(output_path, 'w') as f:
                f.write(notebook)
            
            print(f"   ✅ Saved {name}")

if __name__ == '__main__':
    print("Silver Generator Ready")
