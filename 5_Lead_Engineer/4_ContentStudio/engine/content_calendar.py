"""Content Calendar - LinkedIn Cadence 2026

Audience-led cadence: 13 posts/week (M-Sat 9AM+6PM, Sun 11AM).
Audience rotation: Individuals → Students → Colleges → Corporate → Hiring → Founders.
Morning MESSAGE + Evening PROOF architecture.
"""

import json
from datetime import datetime, timedelta


class ContentCalendar:
    """Generates content calendar following NEW STRATEGY."""
    
    def __init__(self):
        # NEW STRATEGY: 13 posts/week cadence
        # Monday-Saturday: 9AM + 6PM (12 posts)
        # Sunday: 11AM (1 post)
        
        self.weekly_cadence = [
            {"day": "Monday", "slots": ["9AM", "6PM"]},
            {"day": "Tuesday", "slots": ["9AM", "6PM"]},
            {"day": "Wednesday", "slots": ["9AM", "6PM"]},
            {"day": "Thursday", "slots": ["9AM", "6PM"]},
            {"day": "Friday", "slots": ["9AM", "6PM"]},
            {"day": "Saturday", "slots": ["9AM", "6PM"]},
            {"day": "Sunday", "slots": ["11AM"]},
        ]
        
        # Audience rotation (weekly cycle)
        self.audience_rotation = [
            "individuals",
            "students",
            "colleges",
            "corporate",
            "hiring",
            "founders"
        ]
        
        # Time slot rules
        self.slot_rules = {
            "9AM": {"type": "morning", "format": "MESSAGE", "cta": False},
            "6PM": {"type": "evening", "format": "PROOF", "cta": True},
            "11AM": {"type": "mixed", "format": "FLEX", "cta": "optional"}
        }
    
    def generate_month(self, start_date, weeks=4):
        """Generate content calendar following NEW STRATEGY.
        
        Args:
            start_date: Start date (datetime object)
            weeks: Number of weeks to generate (default 4)
        
        Returns:
            List of content items with audience rotation and time slots
        """
        content_items = []
        item_id = 1
        current_date = start_date
        
        for week_num in range(weeks):
            # Rotate audience weekly
            audience = self.audience_rotation[week_num % len(self.audience_rotation)]
            
            for day_schedule in self.weekly_cadence:
                day_name = day_schedule["day"]
                
                for time_slot in day_schedule["slots"]:
                    slot_config = self.slot_rules[time_slot]
                    
                    # Generate content item
                    content_items.append({
                        "id": item_id,
                        "week": week_num + 1,
                        "day": day_name,
                        "time_slot": time_slot,
                        "audience": audience,
                        "slot_type": slot_config["type"],
                        "format": slot_config["format"],
                        "cta_required": slot_config["cta"],
                        "suggested_date": current_date.strftime("%Y-%m-%d"),
                        "platform": "linkedin",
                        "status": "pending",
                        "content": None,  # Generated by ContentEngine
                        "created_at": datetime.now().isoformat()
                    })
                    
                    item_id += 1
                
                # Move to next day
                current_date += timedelta(days=1)
        
        return content_items
